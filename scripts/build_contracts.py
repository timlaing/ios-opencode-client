"""Regenerate route catalog/manifest deterministically from the pinned snapshot."""
import hashlib
import json
import sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from mock.contract import ROOT, OPERATIONS
from mock.server import MODELED, State
from mock.fixtures import BASE_TIME, generate


def build():
    scope = json.loads((ROOT/'contracts/mobile-scope.json').read_text())
    references = {op:[] for op in OPERATIONS}
    for workflow in scope['workflows']:
        for op in workflow['operations']:
            if op not in OPERATIONS:
                raise ValueError(f'Unknown operation {op}')
            references[op].append(workflow['id'])
    stages = {w['id']:w['stage'] for w in scope['workflows']}
    rows = []
    for op,record in sorted(OPERATIONS.items()):
        workflows = references[op]
        stage = 'initial' if any(stages[w].startswith('initial') for w in workflows) else ('later' if workflows else 'outside-mobile-scope')
        rows.append({'operationId':op,'method':record['method'],'path':record['path'],
                     'stage':stage,'workflows':workflows,'mock':'modeled' if op in MODELED else 'not-modeled',
                     'parameters':record.get('parameters',[]),'requestBody':record.get('requestBody'),
                     'responses':record['responses'], 'description':record.get('description','')})
    snapshot = ROOT/'contracts/opencode-v2.0.25.openapi.json'
    manifest = {'repository':'https://github.com/anomalyco/opencode','version':scope['baseline'],'commit':scope['commit'],
                'sourcePath':'packages/protocol/openapi.json','sourceUrl':f'https://github.com/anomalyco/opencode/blob/{scope["commit"]}/packages/protocol/openapi.json',
                'sha256':hashlib.sha256(snapshot.read_bytes()).hexdigest(),'bytes':snapshot.stat().st_size,
                'operationCount':len(rows),'schemaCount':256,'mockModeledOperations':len(MODELED),
                'upstreamLicense':'MIT; see UPSTREAM-LICENSE','evidence':'Pinned source/OpenAPI; mock tests are not live-server tests'}
    (ROOT/'contracts/source-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    (ROOT/'contracts/route-catalog.json').write_text(json.dumps(rows,indent=2)+'\n')
    lines = ['# Generated OpenCode route catalog','',
             'Generated by `python3 scripts/build_contracts.py`. The complete request/response schemas are in the [OpenAPI snapshot](../contracts/opencode-v2.0.25.openapi.json); this index does not replace them.',
             '',f'Pinned baseline: v{scope["baseline"]}, `{scope["commit"]}`. Workflows and screen IDs are defined in the [API contract](api-contract.md) and [screen specification](navigation-screens.md).',
             '', '“Modeled” means synthetic behavior exists, not that every operation is equivalent to a live server. See [mock limitations](testing-mock.md#fidelity-and-limits). Unmodelled routes return mock-only 501, not a fabricated success.',
             '', '| Operation | Method/path | Stage | Workflow | Mock |','| --- | --- | --- | --- | --- |']
    for r in rows:
        lines.append(f'| `{r["operationId"]}` | `{r["method"]} {r["path"]}` | {r["stage"]} | {", ".join(r["workflows"]) or "—"} | {r["mock"]} |')
    (ROOT/'docs/api-route-catalog.md').write_text('\n'.join(lines)+'\n')
    fixture = generate()
    cases = [
        {'operationId':'project.list','method':'GET','path':'/api/project','expectedStatus':200,'expected':fixture['projects']},
        {'operationId':'session.get','method':'GET','path':'/api/session/ses_demo_001','expectedStatus':200,'expected':{'data':fixture['sessions']['ses_demo_001']}},
        {'operationId':'session.prompt','method':'POST','path':'/api/session/ses_demo_007/prompt',
         'body':{'id':'msg_example_queued','text':'Review **the synthetic project**','delivery':'queue','resume':False},'expectedStatus':200},
        {'operationId':'session.permission.reply','method':'POST','path':'/api/session/ses_demo_002/permission/per_demo/reply',
         'body':{'decision':'once'},'expectedStatus':204},
        {'operationId':'session.form.reply','method':'POST','path':'/api/session/ses_demo_003/form/frm_demo/reply',
         'body':{'answer':{'environment':'production','confirm':True,'checks':['unit']}},'expectedStatus':204},
        {'operationId':'experimental.mcp.disconnect','method':'POST','path':'/api/experimental/mcp/demo-docs/disconnect','expectedStatus':204},
        {'operationId':'session.update','method':'PATCH','path':'/api/session/ses_demo_001','body':{'title':'Renamed synthetic session'},'expectedStatus':204},
    ]
    (ROOT/'fixtures/generated/http-cases.json').write_text(json.dumps(cases,ensure_ascii=False,indent=2)+'\n')
    state = State(clock=lambda:BASE_TIME/1000)
    _, admitted = state.dispatch('session.prompt',{'sessionID':'ses_demo_007'},{},
                                {'id':'msg_trace','text':'Generate the offline SSE trace','resume':False})
    state.active.add('ses_demo_007')
    state.runs['ses_demo_007'] = 1
    state.execute('ses_demo_007',admitted['data'],'normal',1,state.generation)
    events = [{'id':'evt_mock_connected','type':'server.connected','data':{}},*state.events]
    (ROOT/'fixtures/generated/events.jsonl').write_text(''.join(json.dumps(e,ensure_ascii=False)+'\n' for e in events))
    (ROOT/'fixtures/generated/events.sse').write_text(': heartbeat\n\n'+''.join('data: '+json.dumps(e,ensure_ascii=False)+'\n\n' for e in events))
    print(f'Generated {len(rows)} operations; {len(MODELED)} have synthetic behavior.')


if __name__ == '__main__':
    build()
